def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def gradient(w, h, c1, c2, diagonal=True):
    a, b = hex2rgb(c1), hex2rgb(c2)
    img = Image.new("RGB", (w, h))
    px = img.load()
    for y in range(h):
        for x in range(w):
            t = ((x / w + y / h) / 2) if diagonal else y / h
            px[x, y] = tuple(int(a[i] * (1 - t) + b[i] * t) for i in range(3))
    return img


def draw_glyph(d, kind, box, color=(255, 255, 255), width=None):
    """Simple geometric glyphs, drawn from scratch."""
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    cx, cy = x0 + w / 2, y0 + h / 2
    lw = width or max(2, int(w * 0.09))
    if kind == "leaf":
        d.ellipse([x0 + w * .18, y0 + h * .05, x1 - w * .18, y1 - h * .05], outline=color, width=lw)
        d.line([cx, y0 + h * .12, cx, y1 - h * .02], fill=color, width=lw)
        for k in (.35, .55, .75):
            d.line([cx, y0 + h * k, cx + w * .18, y0 + h * (k - .12)], fill=color, width=max(2, lw // 2))
            d.line([cx, y0 + h * k, cx - w * .18, y0 + h * (k - .12)], fill=color, width=max(2, lw // 2))
    elif kind == "star":
        import math
        pts = []
        for i in range(10):
            r = (w / 2) * (1 if i % 2 == 0 else .45)
            a = -math.pi / 2 + i * math.pi / 5
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
        d.polygon(pts, fill=color)
    elif kind == "bolt":
        d.polygon([(cx + w * .1, y0), (x0 + w * .15, cy + h * .08), (cx, cy + h * .08),
                   (cx - w * .1, y1), (x1 - w * .15, cy - h * .08), (cx, cy - h * .08)], fill=color)
    elif kind == "orbit":
        d.ellipse([x0, cy - h * .2, x1, cy + h * .2], outline=color, width=lw)
        d.ellipse([cx - w * .17, cy - h * .17, cx + w * .17, cy + h * .17], fill=color)
        d.ellipse([x1 - w * .14, cy - h * .3, x1 - w * .02, cy - h * .18], fill=color)
    elif kind == "wave":
        n = 5
        bw = w / (n * 1.7)
        for i, k in enumerate([.35, .7, 1, .6, .4]):
            bx = x0 + i * bw * 1.7 + bw * .35
            d.rounded_rectangle([bx, cy - h / 2 * k, bx + bw, cy + h / 2 * k], radius=bw / 2, fill=color)
    elif kind == "grid":
        s = w / 3.4
        for r in range(3):
            for c in range(3):
                if (r, c) in [(0, 1), (1, 2), (2, 0), (2, 1), (2, 2)]:
                    gx, gy = x0 + c * s * 1.2, y0 + r * s * 1.2
                    d.rounded_rectangle([gx, gy, gx + s, gy + s], radius=s * .2, fill=color)


def channel_logo(ch, size=512):
    """Rounded-square logo with glyph and wordmark."""
    cid, name, group, (c1, c2), glyph = ch
    scale = 4
    S = size * scale
    bg = gradient(S // 8, S // 8, c1, c2).resize((S, S), Image.BICUBIC).convert("RGBA")
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, S - 1, S - 1], radius=S * .22, fill=255)
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    img.paste(bg, (0, 0), mask)
    d = ImageDraw.Draw(img)
    g = S * .36
    draw_glyph(d, glyph, (S / 2 - g / 2, S * .16, S / 2 + g / 2, S * .16 + g))
    word = name.split()[0].upper()
    f = font(int(S * .15))
    tw = d.textlength(word, font=f)
    d.text(((S - tw) / 2, S * .62), word, font=f, fill="white")
    f2 = font(int(S * .065), "SemiBold")
    sub = name.split()[1].upper()
    tw2 = d.textlength(sub, font=f2)
    d.text(((S - tw2) / 2, S * .8), sub, font=f2, fill=(255, 255, 255, 210))
    return img.resize((size, size), Image.LANCZOS)


def movie_poster(m, w=600, h=900):
    mid, title, genre, (c1, c2) = m
    img = gradient(w // 6, h // 6, c1, c2, diagonal=False).resize((w, h), Image.BICUBIC).convert("RGBA")
    d = ImageDraw.Draw(img, "RGBA")
    import random
    rnd = random.Random(mid)
    if mid == "quiet-orbit":
        for _ in range(140):
            x, y, r = rnd.random() * w, rnd.random() * h * .7, rnd.random() * 2.2
            d.ellipse([x - r, y - r, x + r, y + r], fill=(255, 255, 255, int(120 + rnd.random() * 135)))
        d.ellipse([w * .2, h * .18, w * .8, h * .58], fill=(129, 140, 248, 255))
        d.ellipse([w * .08, h * .34, w * .92, h * .42], outline=(224, 231, 255, 220), width=6)
    elif mid == "paper-lanterns":
        for _ in range(16):
            x, y = rnd.random() * w, rnd.random() * h * .62
            s = 20 + rnd.random() * 46
            d.rounded_rectangle([x, y, x + s * .8, y + s], radius=s * .3, fill=(251, 191, 36, int(140 + rnd.random() * 100)))
    else:
        for i in range(7):
            yy = h * (.2 + i * .07)
            d.arc([-w * .2, yy, w * 1.2, yy + h * .25], 200, 340, fill=(204, 251, 241, 120 + i * 15), width=5)
    d.rectangle([0, h * .66, w, h], fill=(0, 0, 0, 120))
    f = font(int(w * .1))
    lines = title.upper().split()
    y = h * .7
    for line in lines:
        tw = d.textlength(line, font=f)
        d.text(((w - tw) / 2, y), line, font=f, fill="white")
        y += w * .115
    f2 = font(int(w * .045), "Medium")
    tag = f"AN AENV DEMO FILM  ·  {genre.upper()}"
    d.text(((w - d.textlength(tag, font=f2)) / 2, h * .93), tag, font=f2, fill=(255, 255, 255, 200))
    return img.convert("RGB")
